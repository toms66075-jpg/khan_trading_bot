# -*- coding: utf-8 -*-
"""
اسکریپت آزادسازی هوش خان‌یار و حذف قفل اجباری ترید
Khan Trading Bot -> Universal Quasar AI
"""
import os
import re

TARGET_FILE = "main.py"

if not os.path.exists(TARGET_FILE):
    print("[-] خطا: فایل main.py پیدا نشد! مطمئن شو این اسکریپت کنار main.py اجرا شده.")
    exit(1)

with open(TARGET_FILE, "r", encoding="utf-8") as f:
    content = f.read()

# پرامپت اختصاصی و منعطف خان‌یار
QUASAR_PROMPT = """تو «خان‌یار» هستی؛ یک دستیار همه‌فن‌حریف، تیز، فوق‌العاده باهوش، مشتی و باحال در تلگرام.
قوانین شخصیتی و رفتاری تو:
۱. لحن: خودمانی، گرم، مشتی، لاتی، صمیمی، بدون تعارف‌های خشک و رسمی، و بدون سلام/خداحافظی‌های کلیشه‌ای.
۲. درباره هر موضوعی که کاربر بگوید (دردودل، شوخی، کل‌کل، کدنویسی، رفع ارور، تکنولوژی، فلسفه، انگیزه، روزمرگی، آشپزی یا هر چیز دیگر) کاملاً مسلط، پرانرژی و جذاب صحبت کن.
۳. قانون طلایی: تا زمانی که کاربر خودش صریحاً اسم جفت‌ارز، کریپتو، طلا، فارکس یا تحلیل تکنیکال نیاورده و یا عکسی از چارت نفرستاده، ابداً و اصلاً پای ترید را وسط نکش! مثل یک هوش مصنوعی عمومی و رفیق همه‌کاره گپ بزن.
۴. اگر کاربر عکسی از چارت فرستاد یا درباره ارز/ترید سوال کرد، درجا تبدیل به غول تحلیلگری سبک ICT و SMC شو و تمام ساختار بازار (BOS, CHoCH, FVG, نقدینگی، SL و TP دقیق) را با بالاترین کیفیت استخراج کن.
۵. صاف برو سر اصل مطلب، جذاب و خلاصه پاسخ بده و از روده درازی خودداری کن."""

# 1. جایگزینی پرامپت‌های سیستم
patterns = [
    r'SYSTEM_PROMPT\s*=\s*(?:f?["\']{3}[\s\S]*?["\']{3}|f?["\'].*?["\'])',
    r'SYSTEM_INSTRUCTION\s*=\s*(?:f?["\']{3}[\s\S]*?["\']{3}|f?["\'].*?["\'])',
    r'PROMPT\s*=\s*(?:f?["\']{3}[\s\S]*?["\']{3}|f?["\'].*?["\'])',
    r'BASE_PROMPT\s*=\s*(?:f?["\']{3}[\s\S]*?["\']{3}|f?["\'].*?["\'])'
]

found_prompt = False
for pat in patterns:
    if re.search(pat, content):
        content = re.sub(pat, f'SYSTEM_PROMPT = """{QUASAR_PROMPT}"""', content, count=1)
        found_prompt = True
        break

if not found_prompt:
    content = f'SYSTEM_PROMPT = """{QUASAR_PROMPT}"""\n' + content

# 2. اصلاح ساختار ارسال پیام به مدل در صورت اضافه کردن اجباری پیش‌فرض‌های ترید
# برخی کدها کاربر هر متنی بفرستد می‌نویسند: f"تحلیل ارز {user_text}" یا "تحلیل ترید: {user_text}"
content = re.sub(r'f?["\']لطفاً تحلیل (?:تکنیکال )?ارز ["\']\s*\+\s*message\.text', 'message.text', content)
content = re.sub(r'f?["\']تحلیل (?:مارکت|ترید|ارز):?\s*\{([^}]+)\}', r'{\1}', content)

# 3. پاکسازی جملات بازدارنده قدیمی
bad_sentences = [
    "ارز مورد نظر را جهت بررسی ارسال کنید",
    "لطفا جفت ارز یا نماد مورد نظر خود را ارسال کنید",
    "جهت تحلیل، نام نماد معاملاتی را بفرستید",
    "لطفاً یک نماد ترید ارسال کنید"
]

for s in bad_sentences:
    if s in content:
        content = content.replace(s, "جانم ستون، بگو در خدمتم!")

# ذخیره نسخه نهایی
with open(TARGET_FILE, "w", encoding="utf-8") as f:
    f.write(content)

print("="*50)
print("[+] قفل ترید با موفقیت ۱۰۰٪ شکسته شد!")
print("[+] ربات اکنون مانند خان‌یار همه‌کاره شد و فقط در صورت درخواست به موضوع ترید می‌پردازد.")
print("[+] حالا دستور زیر را در CMD اجرا کن:")
print("python main.py")
print("="*50)
